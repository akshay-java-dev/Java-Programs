
public class LargestOfTwo {
    public static void main(String[] args) {
        int a = 50;
        int b = 30;

        if (a > b) {
            System.out.println(a + " is largest");
        } else if (b > a) {
            System.out.println(b + " is largest");
        } else {
            System.out.println("Both are equal");
        }
    }
}
